function normalizeScholarshipItem(s: any): Scholarship {
  const isNational =
    !s.states ||
    s.states.includes("all") ||
    (s.location && s.location.toLowerCase().includes("united states")) ||
    s.location === "Nationwide";

  let loc = s.location;
  if (!loc) {
    if (isNational) {
      loc = "Nationwide";
    } else if (s.states && s.states.length > 0) {
      loc = s.states
        .map((st: string) => st.charAt(0).toUpperCase() + st.slice(1).replace(/-/g, " "))
        .join(", ");
    } else {
      loc = "Nationwide";
    }
  }

  const providerName = s.provider || (s.source ? s.source : s.organization ? s.organization : "scholarships.com");
  const sourceName = s.source || s.provider || "scholarships.com";

  let fieldLabel = s.field_of_study;
  if (!fieldLabel) {
    if (!s.fields || s.fields.includes("all")) {
      fieldLabel = "All Disciplines / General";
    } else {
      fieldLabel = s.fields
        .map((f: string) => f.charAt(0).toUpperCase() + f.slice(1).replace(/-/g, " "))
        .join(", ");
    }
  }

  let levelLabel = s.level;
  if (!levelLabel) {
    if (s.schoolYears?.includes("high-school-sophomore") && s.schoolYears?.includes("high-school-freshman")) {
      levelLabel = "High School (All Grades)";
    } else if (s.schoolYears?.includes("high-school-senior")) {
      levelLabel = "High School Senior";
    } else {
      levelLabel = "High School & College";
    }
  }

  const minGpa = typeof s.min_gpa === "number" ? s.min_gpa : (typeof s.gpaRequirement === "number" ? s.gpaRequirement : 0);
  const schoolYears = Array.isArray(s.schoolYears) && s.schoolYears.length > 0 ? s.schoolYears : ["all"];
  const states = Array.isArray(s.states) && s.states.length > 0 ? s.states : ["all"];
  const fields = Array.isArray(s.fields) && s.fields.length > 0 ? s.fields : ["all"];
  const ethnicity = Array.isArray(s.ethnicity) && s.ethnicity.length > 0 ? s.ethnicity : ["all"];

  return {
    ...s,
    provider: providerName,
    source: sourceName,
    field_of_study: fieldLabel,
    level: levelLabel,
    location: loc,
    scraped_at: s.scraped_at || "2026-10-25T12:00:00Z",
    minimunGpa: minGpa,
    gpaRequirement: minGpa,
    schoolYears,
    states,
    fields,
    ethnicity,
    url: s.url || s.applicationUrl || "https://www.scholarships.com",
    applicationUrl: s.applicationUrl || s.url || "https://www.scholarships.com",
  };
}

export const SCHOLARSHIPS_DATA: Scholarship[] = RAW_SCHOLARSHIPS.map(normalizeScholarshipItem);
